"""SupplyChain IQ - Planning Runs, Shortages, Mitigation Options & Decisions."""

from datetime import datetime
from decimal import Decimal
from typing import List, Optional
import uuid

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from backend.app.models.base import (
    Base,
    GUID,
    PrimaryKeyMixin,
    TimestampMixin,
    utc_now,
)
from backend.app.models.enums import (
    MitigationActionType,
    MitigationDecisionType,
    MitigationOptionStatus,
    PlanningRunStatus,
    ShortageSeverity,
    ShortageStatus,
)


class PlanningRun(Base, PrimaryKeyMixin, TimestampMixin):
    """Immutable execution instance of the MRP engine and optimization run."""
    __tablename__ = "planning_runs"

    run_number: Mapped[int] = mapped_column(Integer, unique=True, index=True, nullable=False)
    status: Mapped[PlanningRunStatus] = mapped_column(String(32), default=PlanningRunStatus.QUEUED, index=True, nullable=False)
    horizon_weeks: Mapped[int] = mapped_column(Integer, default=26, nullable=False)
    started_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    config_json: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    summary_json: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    is_superseded: Mapped[bool] = mapped_column(Boolean, default=False, index=True, nullable=False)

    __table_args__ = (
        CheckConstraint("run_number >= 1", name="ck_planning_run_number_positive"),
        CheckConstraint("horizon_weeks >= 1 AND horizon_weeks <= 104", name="ck_planning_run_horizon_range"),
    )

    # Relationships
    shortages: Mapped[List["Shortage"]] = relationship("Shortage", back_populates="planning_run", cascade="all, delete-orphan")


class Shortage(Base, PrimaryKeyMixin, TimestampMixin):
    """Identified projected stockout or safety stock breach event."""
    __tablename__ = "shortages"

    planning_run_id: Mapped[uuid.UUID] = mapped_column(GUID, ForeignKey("planning_runs.id", ondelete="CASCADE"), index=True, nullable=False)
    sku_id: Mapped[uuid.UUID] = mapped_column(GUID, ForeignKey("skus.id", ondelete="RESTRICT"), index=True, nullable=False)
    location_id: Mapped[uuid.UUID] = mapped_column(GUID, ForeignKey("locations.id", ondelete="RESTRICT"), index=True, nullable=False)
    week_bucket: Mapped[str] = mapped_column(String(16), index=True, nullable=False)
    projected_deficit_qty: Mapped[int] = mapped_column(Integer, nullable=False)
    demand_shortage_qty: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    safety_stock_gap_qty: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    severity: Mapped[ShortageSeverity] = mapped_column(String(32), index=True, nullable=False)
    priority_tier: Mapped[Optional[str]] = mapped_column(String(32), index=True, nullable=True)
    priority_score: Mapped[Decimal] = mapped_column(Numeric(5, 2), default=Decimal("0.00"), index=True, nullable=False)
    financial_impact: Mapped[Decimal] = mapped_column(Numeric(14, 2), default=Decimal("0.00"), nullable=False)
    root_cause: Mapped[Optional[str]] = mapped_column(String(64), index=True, nullable=True)
    root_cause_explanation: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    details_json: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    status: Mapped[ShortageStatus] = mapped_column(String(32), default=ShortageStatus.DETECTED, index=True, nullable=False)

    __table_args__ = (
        UniqueConstraint("planning_run_id", "sku_id", "location_id", "week_bucket", name="uq_shortage_event"),
        CheckConstraint("projected_deficit_qty > 0", name="ck_shortage_deficit_positive"),
        CheckConstraint("priority_score >= 0.0 AND priority_score <= 100.0", name="ck_shortage_priority_score_range"),
        Index("ix_shortage_run_priority", "planning_run_id", "priority_score"),
        Index("ix_shortage_sku_loc_week", "sku_id", "location_id", "week_bucket"),
    )

    # Relationships
    planning_run: Mapped["PlanningRun"] = relationship("PlanningRun", back_populates="shortages")
    sku: Mapped["SKU"] = relationship("SKU", back_populates="shortages")
    location: Mapped["Location"] = relationship("Location", back_populates="shortages")
    mitigation_options: Mapped[List["MitigationOption"]] = relationship("MitigationOption", back_populates="shortage", cascade="all, delete-orphan")


class MitigationOption(Base, PrimaryKeyMixin, TimestampMixin):
    """Recommended feasible mitigation action generated by the optimization engine."""
    __tablename__ = "mitigation_options"

    shortage_id: Mapped[uuid.UUID] = mapped_column(GUID, ForeignKey("shortages.id", ondelete="CASCADE"), index=True, nullable=False)
    action_type: Mapped[MitigationActionType] = mapped_column(String(32), index=True, nullable=False)
    status: Mapped[MitigationOptionStatus] = mapped_column(String(32), default=MitigationOptionStatus.PROPOSED, index=True, nullable=False)
    recommended_qty: Mapped[int] = mapped_column(Integer, nullable=False)
    source_reference_id: Mapped[Optional[str]] = mapped_column(String(128), nullable=True)  # PO id, Supplier id, or Transfer origin
    incremental_cost: Mapped[Decimal] = mapped_column(Numeric(14, 2), default=Decimal("0.00"), nullable=False)
    service_gain_score: Mapped[Decimal] = mapped_column(Numeric(5, 2), default=Decimal("100.00"), nullable=False)
    roi_ratio: Mapped[Decimal] = mapped_column(Numeric(10, 4), default=Decimal("0.0000"), nullable=False)
    rank: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    details_json: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    __table_args__ = (
        UniqueConstraint("shortage_id", "rank", name="uq_mitigation_option_rank"),
        CheckConstraint("recommended_qty > 0", name="ck_mitigation_recommended_qty_positive"),
        CheckConstraint("incremental_cost >= 0", name="ck_mitigation_cost_non_negative"),
        CheckConstraint("service_gain_score >= 0.0 AND service_gain_score <= 100.0", name="ck_mitigation_service_gain_range"),
        CheckConstraint("rank >= 1", name="ck_mitigation_rank_positive"),
    )

    # Relationships
    shortage: Mapped["Shortage"] = relationship("Shortage", back_populates="mitigation_options")
    decisions: Mapped[List["MitigationDecision"]] = relationship("MitigationDecision", back_populates="mitigation_option", cascade="all, delete-orphan")


class MitigationDecision(Base, PrimaryKeyMixin, TimestampMixin):
    """Planner decision record approving, modifying, or rejecting a mitigation option."""
    __tablename__ = "mitigation_decisions"

    mitigation_option_id: Mapped[uuid.UUID] = mapped_column(GUID, ForeignKey("mitigation_options.id", ondelete="RESTRICT"), index=True, nullable=False)
    planner_id: Mapped[str] = mapped_column(String(64), index=True, nullable=False)
    decision: Mapped[MitigationDecisionType] = mapped_column(String(32), index=True, nullable=False)
    override_qty: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    reason: Mapped[str] = mapped_column(Text, nullable=False)
    decided_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        CheckConstraint("override_qty IS NULL OR override_qty > 0", name="ck_mitigation_decision_override_positive"),
    )

    # Relationships
    mitigation_option: Mapped["MitigationOption"] = relationship("MitigationOption", back_populates="decisions")

